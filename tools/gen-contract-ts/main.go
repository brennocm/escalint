// Command gen-contract-ts generates web/src/contract/analysis.ts from
// schema/analysis.v1.schema.json (ADR 0003). It supports the subset of
// JSON Schema the contract uses: objects with additionalProperties false or
// a value schema, arrays, string enums, const, $ref, oneOf and nullable
// type lists. Anything else is an error, so the schema cannot silently use
// a construct the generator ignores.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"
	"unicode"
)

type schema struct {
	Ref                  string             `json:"$ref"`
	Type                 any                `json:"type"`
	Enum                 []any              `json:"enum"`
	Const                any                `json:"const"`
	Properties           map[string]*schema `json:"properties"`
	Required             []string           `json:"required"`
	AdditionalProperties any                `json:"additionalProperties"`
	Items                *schema            `json:"items"`
	OneOf                []*schema          `json:"oneOf"`
	Description          string             `json:"description"`
	Defs                 map[string]*schema `json:"$defs"`
	// Validation-only keywords, ignored by the generator.
	Pattern     string   `json:"pattern"`
	Format      string   `json:"format"`
	Minimum     *float64 `json:"minimum"`
	Maximum     *float64 `json:"maximum"`
	MinItems    *int     `json:"minItems"`
	UniqueItems bool     `json:"uniqueItems"`
	Schema      string   `json:"$schema"`
	ID          string   `json:"$id"`
	Title       string   `json:"title"`
}

func main() {
	in := flag.String("schema", "schema/analysis.v1.schema.json", "schema file")
	out := flag.String("out", "web/src/contract/analysis.ts", "output file")
	flag.Parse()
	if err := run(*in, *out); err != nil {
		fmt.Fprintln(os.Stderr, "gen-contract-ts:", err)
		os.Exit(1)
	}
}

func run(in, out string) error {
	raw, err := os.ReadFile(in) // #nosec G304 -- developer-supplied path
	if err != nil {
		return err
	}
	ts, err := generate(raw)
	if err != nil {
		return err
	}
	return os.WriteFile(out, ts, 0o600)
}

func generate(raw []byte) ([]byte, error) {
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.DisallowUnknownFields()
	var root schema
	if err := dec.Decode(&root); err != nil {
		return nil, fmt.Errorf("schema uses an unsupported keyword: %w", err)
	}
	var b strings.Builder
	b.WriteString("// Code generated by tools/gen-contract-ts from schema/analysis.v1.schema.json. DO NOT EDIT.\n")
	b.WriteString("// Run `pnpm gen:contract` (or `make gen`) after changing the schema.\n\n")
	g := gen{b: &b}
	if err := g.declare("Analysis", &root); err != nil {
		return nil, err
	}
	names := make([]string, 0, len(root.Defs))
	for n := range root.Defs {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		b.WriteString("\n")
		if err := g.declare(typeName(n), root.Defs[n]); err != nil {
			return nil, fmt.Errorf("$defs/%s: %w", n, err)
		}
	}
	if v, ok := root.Properties["schema_version"]; ok && v.Const != nil {
		fmt.Fprintf(&b, "\nexport const SCHEMA_VERSION = %s;\n", literal(v.Const))
	}
	return []byte(b.String()), nil
}

type gen struct{ b *strings.Builder }

func (g gen) declare(name string, s *schema) error {
	if s.Description != "" && s.Ref == "" {
		fmt.Fprintf(g.b, "/** %s */\n", s.Description)
	}
	if isObject(s) && s.Properties != nil {
		body, err := g.object(s, "")
		if err != nil {
			return err
		}
		fmt.Fprintf(g.b, "export interface %s %s\n", name, body)
		return nil
	}
	t, err := g.expr(s, "")
	if err != nil {
		return err
	}
	fmt.Fprintf(g.b, "export type %s = %s;\n", name, t)
	return nil
}

func isObject(s *schema) bool {
	t, _ := s.Type.(string)
	return t == "object"
}

func (g gen) object(s *schema, indent string) (string, error) {
	if s.AdditionalProperties != false {
		return "", errors.New("objects with properties must set additionalProperties: false")
	}
	required := map[string]bool{}
	for _, r := range s.Required {
		required[r] = true
	}
	keys := make([]string, 0, len(s.Properties))
	for k := range s.Properties {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("{\n")
	for _, k := range keys {
		p := s.Properties[k]
		if p.Description != "" {
			fmt.Fprintf(&b, "%s  /** %s */\n", indent, p.Description)
		}
		t, err := g.expr(p, indent+"  ")
		if err != nil {
			return "", fmt.Errorf("%s: %w", k, err)
		}
		opt := ""
		if !required[k] {
			opt = "?"
		}
		fmt.Fprintf(&b, "%s  readonly %s%s: %s;\n", indent, k, opt, t)
	}
	b.WriteString(indent + "}")
	return b.String(), nil
}

func (g gen) expr(s *schema, indent string) (string, error) {
	switch {
	case s.Ref != "":
		name, ok := strings.CutPrefix(s.Ref, "#/$defs/")
		if !ok {
			return "", fmt.Errorf("unsupported $ref %q", s.Ref)
		}
		return typeName(name), nil
	case s.Const != nil:
		return literal(s.Const), nil
	case len(s.OneOf) > 0:
		var parts []string
		for _, o := range s.OneOf {
			t, err := g.expr(o, indent)
			if err != nil {
				return "", err
			}
			parts = append(parts, t)
		}
		return strings.Join(parts, " | "), nil
	case len(s.Enum) > 0:
		var parts []string
		for _, v := range s.Enum {
			parts = append(parts, literal(v))
		}
		return strings.Join(parts, " | "), nil
	}
	types, err := typeList(s.Type)
	if err != nil {
		return "", err
	}
	var parts []string
	for _, t := range types {
		switch t {
		case "string":
			parts = append(parts, "string")
		case "integer", "number":
			parts = append(parts, "number")
		case "boolean":
			parts = append(parts, "boolean")
		case "null":
			parts = append(parts, "null")
		case "array":
			if s.Items == nil {
				return "", errors.New("array without items")
			}
			item, err := g.expr(s.Items, indent)
			if err != nil {
				return "", err
			}
			if strings.Contains(item, " ") {
				item = "(" + item + ")"
			}
			parts = append(parts, "readonly "+item+"[]")
		case "object":
			if s.Properties != nil {
				body, err := g.object(s, indent)
				if err != nil {
					return "", err
				}
				parts = append(parts, body)
				continue
			}
			if s.AdditionalProperties == nil {
				parts = append(parts, "Readonly<Record<string, unknown>>") // free-form JSON object
				continue
			}
			vs, ok := s.AdditionalProperties.(map[string]any)
			if !ok {
				return "", errors.New("map objects need an additionalProperties schema")
			}
			vt, _ := vs["type"].(string)
			if vt != "string" {
				return "", errors.New("only string-valued maps are supported")
			}
			parts = append(parts, "Readonly<Record<string, string>>")
		default:
			return "", fmt.Errorf("unsupported type %q", t)
		}
	}
	return strings.Join(parts, " | "), nil
}

func typeList(t any) ([]string, error) {
	switch v := t.(type) {
	case string:
		return []string{v}, nil
	case []any:
		var out []string
		for _, x := range v {
			s, ok := x.(string)
			if !ok {
				return nil, errors.New("type list must hold strings")
			}
			out = append(out, s)
		}
		return out, nil
	}
	return nil, fmt.Errorf("schema without a supported type: %v", t)
}

func literal(v any) string {
	if v == nil {
		return "null"
	}
	data, err := json.Marshal(v)
	if err != nil {
		panic(err) // values come from decoded JSON
	}
	return string(data)
}

// typeName turns a $defs key into a TypeScript type name.
func typeName(s string) string {
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}
